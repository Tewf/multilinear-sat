"""The fidelity experiment's markdown table, from its JSONL records."""
SURROGATES = ["log_F", "mu", "logsum", "pair"]


def median(values):
    ordered = sorted(values)
    middle = len(ordered) // 2
    return ordered[middle] if len(ordered) % 2 else (ordered[middle - 1] + ordered[middle]) / 2


def write_table(records, path, arguments):
    lines = [
        "# Fidelity of the surrogates to the exact log P(all satisfied)",
        "",
        f"Generated by `fidelity.py` (steps={arguments.steps}, batch={arguments.batch_size}, "
        f"device={arguments.device}); points sampled every 25 steps of the F, mu and fourier "
        "trajectories, 4 slots each; exact values and gradients from one SDD compilation per "
        "instance (`exact_count.py`). Spearman and slope are against the exact value over the "
        "instance's points; the cosine is per point, median reported.",
        "",
    ]
    families = dict.fromkeys(record["family"] for record in records)
    for family in families:
        rows = [record for record in records if record["family"] == family]
        lines += [f"## {family} ({len(rows)} instances)", "",
                  "| instance | points | " + " | ".join(
                      f"rho {name} | cos {name} | slope {name}" for name in SURROGATES) + " |",
                  "|---" * (2 + 3 * len(SURROGATES)) + "|"]
        for record in rows:
            cells = [record["instance"], str(record["points"])]
            for name in SURROGATES:
                cells += [f"{record[name]['spearman']:.3f}", f"{record[name]['cosine_median']:.3f}",
                          f"{record[name]['slope']:.3f}"]
            lines.append("| " + " | ".join(cells) + " |")
        cells = ["**median**", str(median([record["points"] for record in rows]))]
        for name in SURROGATES:
            for field in ("spearman", "cosine_median", "slope"):
                cells.append(f"**{median([record[name][field] for record in rows]):.3f}**")
        lines += ["| " + " | ".join(cells) + " |", ""]
    path.write_text("\n".join(lines))
